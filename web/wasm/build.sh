#!/usr/bin/env bash
# Builds the software ASTC decoder (astc_decode.cpp) to WebAssembly, and writes it inline into
# src/astc-wasm.ts. Needs Emscripten (emcc). The output is committed, so `npm run build` doesn't
# need it; rerun this after changing the decoder.
set -euo pipefail

cd "$(dirname "$0")"
DECODER_DIR=../../android/src/main/cpp
OUT=build
mkdir -p "$OUT"

emcc -O3 -flto -msimd128 -DNDEBUG -std=c++17 -fno-exceptions -fno-rtti \
  -I"$DECODER_DIR" astc_decode.cpp "$DECODER_DIR/astc_decomp.cpp" \
  --no-entry -sSTANDALONE_WASM -sFILESYSTEM=0 -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=4MB \
  -sEXPORTED_FUNCTIONS=_astc_alloc,_astc_free,_astc_decode_layer \
  -o "$OUT/astc.wasm"

{
  echo "// Generated by wasm/build.sh from wasm/astc_decode.cpp; do not edit."
  echo "export const ASTC_WASM_BASE64 ="
  echo "  '$(base64 < "$OUT/astc.wasm" | tr -d '\n')';"
} > ../src/astc-wasm.ts

echo "astc.wasm: $(wc -c < "$OUT/astc.wasm") bytes"
